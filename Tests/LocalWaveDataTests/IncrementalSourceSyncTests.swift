import Foundation
import SQLite
import XCTest
import LocalWaveCore
import LocalWaveDomain
@testable import LocalWaveData

final class IncrementalSourceSyncTests: XCTestCase {
    func testFileAndSubtreeChangesLeaveUnrelatedPathsUntouched() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let untouched = root.appendingPathComponent("Untouched")
        try FileManager.default.createDirectory(at: untouched, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        try Data([1]).write(to: untouched.appendingPathComponent("keep.flac"))
        let db = try Connection(.inMemory)
        let sources = try SQLiteSourceRepository(db: db)
        let paths = try SQLiteSourcePathRepository(db: db)
        let search = try SQLiteSourcePathSearchRepository(db: db)
        let access = SourceAccess(repository: sources)
        let source = try await sources.create(source: Source(id: nil, dirPath: root.path, pathId: makeURLHash(root), userId: 1, type: .iCloud, totalPaths: nil, syncError: nil, isCurrent: true, createdAt: Date(), lastSyncedAt: nil, updatedAt: nil, bookmark: root.bookmarkData(options: sourceBookmarkCreationOptions)))
        let id = try XCTUnwrap(source.id)
        let sync = DefaultSourceSyncService(sourceRepository: sources, sourcePathSearchRepository: search, sourcePathRepository: paths, sourceAccess: access)
        let initial = try await sync.syncDir(sourceId: id, folderURL: root, onCurrentURL: nil, onSetLoading: nil)
        XCTAssertNil(initial?.syncError)
        XCTAssertEqual(initial?.totalPaths, 1)
        try db.execute("CREATE TABLE touched (path TEXT); CREATE TRIGGER trace_paths AFTER UPDATE ON source_paths BEGIN INSERT INTO touched VALUES (new.relativePath); END;")
        // A full traversal would hit this escaping symlink and fail validation.
        try FileManager.default.createSymbolicLink(at: untouched.appendingPathComponent("escape.flac"), withDestinationURL: root.deletingLastPathComponent())
        let album = root.appendingPathComponent("Changes/Album")
        try FileManager.default.createDirectory(at: album, withIntermediateDirectories: true)
        let track = album.appendingPathComponent("new.flac")
        try Data([1, 2]).write(to: track)
        var result = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album/new.flac"])
        XCTAssertEqual(result.source?.totalPaths, 2)
        XCTAssertEqual(result.audioPaths.map(\.relativePath), ["Changes/Album/new.flac"])
        let parent = try await paths.getByPath(relativePath: "Changes/Album", sourceId: id)
        XCTAssertTrue(try XCTUnwrap(parent).isDirectory)
        XCTAssertEqual(try db.scalar("SELECT COUNT(*) FROM touched") as? Int64, 0)
        _ = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album/new.flac"])
        XCTAssertEqual(try db.scalar("SELECT COUNT(*) FROM touched") as? Int64, 0, "An unchanged path must not be rewritten")
        try Data([1, 2, 3]).write(to: track)
        _ = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album/new.flac"])
        XCTAssertEqual(try db.scalar("SELECT path FROM touched") as? String, "Changes/Album/new.flac")
        let renamed = album.appendingPathComponent("renamed.flac")
        try FileManager.default.moveItem(at: track, to: renamed)
        result = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album/new.flac", "Changes/Album/renamed.flac"])
        XCTAssertEqual(result.source?.totalPaths, 2)
        let old = try await paths.getByPath(relativePath: "Changes/Album/new.flac", sourceId: id)
        XCTAssertNil(old)
        let staleSearch = try await search.search(sourceId: id, query: "new", limit: 10)
        XCTAssertTrue(staleSearch.isEmpty)
        let renamedSearch = try await search.search(sourceId: id, query: "renamed", limit: 10)
        XCTAssertEqual(renamedSearch.count, 1)
        try Data([4]).write(to: album.appendingPathComponent("second.mp3"))
        result = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album", "Changes/Album/second.mp3"])
        XCTAssertEqual(result.source?.totalPaths, 3, "Overlapping notifications must not double-count the subtree")
        XCTAssertEqual(Set(result.audioPaths.map(\.name)), ["renamed.flac", "second.mp3"])
        try FileManager.default.removeItem(at: album)
        result = try await sync.syncPaths(sourceId: id, relativePaths: ["Changes/Album"])
        XCTAssertEqual(result.source?.totalPaths, 1)
        XCTAssertTrue(result.audioPaths.isEmpty)
        XCTAssertEqual(try db.scalar("SELECT COUNT(*) FROM source_paths WHERE relativePath LIKE 'Changes/Album%'") as? Int64, 0)
        XCTAssertEqual(try db.scalar("SELECT COUNT(*) FROM source_paths_fts WHERE fullPath LIKE 'Changes/Album%'") as? Int64, 0)
        XCTAssertEqual(try db.scalar("SELECT COUNT(*) FROM touched WHERE path LIKE 'Untouched%'") as? Int64, 0)
        do {
            _ = try await sync.syncPaths(sourceId: id, relativePaths: ["../outside.flac"])
            XCTFail("Escaping changes must be rejected")
        } catch { }
        let kept = try await paths.getByPath(relativePath: "Untouched/keep.flac", sourceId: id)
        XCTAssertNotNil(kept)
        XCTAssertNil(FileHelper(fileURL: URL(fileURLWithPath: root.path + "-sibling/song.flac")).relativePath(from: root))
        XCTAssertEqual(FileHelper(fileURL: root).relativePath(from: root), "")
    }

    func testWatcherCoalescesPathsAndIgnoresAvailabilityOnlyNotifications() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        let sources = try SQLiteSourceRepository(db: Connection(.inMemory))
        let source = try await sources.create(source: Source(id: nil, dirPath: root.path, pathId: makeURLHash(root), userId: 1, type: .iCloud, totalPaths: 0, syncError: nil, isCurrent: true, createdAt: Date(), lastSyncedAt: nil, updatedAt: nil, bookmark: root.bookmarkData(options: sourceBookmarkCreationOptions)))
        let id = try XCTUnwrap(source.id)
        let access = SourceAccess(repository: sources)
        let watched = try await access.rootURL(sourceId: id)
        let first = root.appendingPathComponent("first.flac"), second = root.appendingPathComponent("second.flac")
        try Data([1]).write(to: first)
        try Data([2]).write(to: second)
        await access.beginScan(sourceId: id)
        await access.beginScan(sourceId: id)
        await access.sourceChanged(sourceId: id, watchedRoot: watched, movedRoot: nil, items: [first])
        await access.sourceChanged(sourceId: id, watchedRoot: watched, movedRoot: nil, items: [second])
        await access.endScan(sourceId: id)
        await access.endScan(sourceId: id)
        let changed = await access.takeChangedPaths(sourceId: id)
        XCTAssertEqual(changed, ["first.flac", "second.flac"])
        await access.sourceChanged(sourceId: id, watchedRoot: watched, movedRoot: nil, items: [first, second])
        let unchanged = await access.takeChangedPaths(sourceId: id)
        XCTAssertEqual(unchanged, [], "A provider notification without content changes must not reindex")
        try FileManager.default.removeItem(at: first)
        await access.sourceChanged(sourceId: id, watchedRoot: watched, movedRoot: nil, items: [first])
        let deleted = await access.takeChangedPaths(sourceId: id)
        XCTAssertEqual(deleted, ["first.flac"])
        await access.sourceChanged(sourceId: id, watchedRoot: watched, movedRoot: nil, items: nil)
        let recovery = await access.takeChangedPaths(sourceId: id)
        XCTAssertNil(recovery, "A notification without paths must retain the recovery fallback")
    }
}
